# relational 
#  > , >=, <, <= , ==, != 
a = 5
b = 4

print( a == b)
print(a != b)
print(a > b)

# assignment operator
#   =, +=, -=, *=, /= , %=, **=

print(a)
a += 5
b += 20
print(a)
print(b)

# logical operator
#  not , and, or
# not operator reverse the original value True -> False, False -> True

var = False
print(not var);
print(not (5 < 8))
print((5 > 3) and (8 > 3))
print((5 < 3) or (3 > 6))
